"""失败测乙：对账把未销匣影子当已升格齐套则红。

双写两轨形态：
- 原坏点行进只读归档（坏点状态=已升格/影子），不再算"在匣坏点"。
- 现行入栏改读升格后集合（入栏缓冲带升格指纹）。
- 两轨读引用不同：影子可查但绝不计入现行集合，也不得被对账当成齐套。
"""
from app.services import 装载, 目录, 结栏, 贯验, 升格回放, 夹具


def _匣号(报文编号: str) -> int:
    return next(r["编号"] for r in 目录.坏点列表() if r["报文编号"] == 报文编号)


def test_升格后现行入栏与匣内原行可区分():
    装载.装一批(夹具.读取("坏点可升格成片"))
    匣号 = _匣号("P-bad-a")
    升格回放.升格回放({"坏点编号": [匣号]})

    匣子 = {r["报文编号"]: r for r in 目录.坏点列表()}
    assert 匣子["P-bad-a"]["坏点状态"] == "已升格"
    assert 匣子["P-bad-a"]["升格指纹"]
    # 未升格的仍是现行坏点
    assert 匣子["P-bad-b"]["坏点状态"] == "在匣"

    在匣 = 升格回放.在匣坏点()
    assert {r["报文编号"] for r in 在匣} == {"P-bad-b", "P-bad-c"}
    影子 = 升格回放.归档影子()
    assert {r["报文编号"] for r in 影子} == {"P-bad-a"}


def test_贯验不把未销匣影子当齐套():
    装载.装一批(夹具.读取("坏点可升格成片"))
    匣号 = _匣号("P-bad-a")
    升格回放.升格回放({"坏点编号": [匣号]})

    # 影子行仍在坏点匣表里，但贯验只认"在匣"坏点，影子单列
    快照 = 贯验.只读快照()
    assert 快照["坏点在匣"] == 2
    assert 快照["升格影子"] == 1
    assert 快照["坏点"] == 快照["坏点在匣"], "坏点口径只许是在匣，不含影子"

    # 升格额外贯验：每个升格指纹必须两轨齐（缓冲现行 + 匣内影子），缺边即撕裂
    问题 = 升格回放.额外贯验()
    assert 问题 == [], 问题


def test_缺边影子在贯验里报撕裂():
    装载.装一批(夹具.读取("坏点可升格成片"))
    匣号 = _匣号("P-bad-b")
    报告 = 升格回放.升格回放({"坏点编号": [匣号]})
    指纹 = 报告["指纹"]

    # 手工制造撕裂：影子还在、现行缓冲被抹掉（模拟只销匣不入栏的失败形态）
    from app.db import 连接
    conn = 连接()
    try:
        conn.execute("DELETE FROM 入栏缓冲 WHERE 升格指纹=?", (指纹,))
        conn.commit()
    finally:
        conn.close()

    问题 = 升格回放.额外贯验()
    assert any("缺边" in s or "撕裂" in s for s in 问题), 问题


def test_升格行可正常结栏且贯验对齐():
    装载.装一批(夹具.读取("入栏成汇总样例"))
    装载.装一批(夹具.读取("坏点可升格成片"))
    升格回放.升格回放({"坏点编号": [_匣号("P-bad-a"), _匣号("P-bad-b")]})

    结 = 结栏.结当前栏()
    assert 结["缓冲消耗"] == 5  # 3 条正常入栏 + 2 条升格入栏
    果 = 贯验.跑一次()
    assert 果["是否对齐"] is True
    assert 果["坏点在匣"] == 1   # 仅未升格的 P-bad-c
    assert 果["升格影子"] == 2
    assert 升格回放.额外贯验() == []


def test_成片升格同票原子成败():
    装载.装一批(夹具.读取("坏点可升格成片"))
    真号 = _匣号("P-bad-a")
    前 = len(目录.坏点列表())

    # 一票里夹一个不存在的匣号：整票回滚，不允许半票升格
    try:
        升格回放.升格回放({"坏点编号": [真号, 999999]})
        raised = False
    except ValueError:
        raised = True
    assert raised
    assert len(目录.坏点列表()) == 前
    assert 目录.缓冲列表() == []
    assert 升格回放.只读() == []
