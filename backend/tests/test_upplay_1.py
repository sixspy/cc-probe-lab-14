"""失败测甲：升格后正式又复制出第二条同号入栏则红。

骨签 probe-14 · 坏点升格回放
约束：
- 升格回放不是全新报文，原旁路键（原报文编号）必须随行，命运对得上二次。
- 切流账册钉升格指纹；无指纹/无键回放一律拒绝。
- 同号新装、同指纹二次回放都必须被幂等驳回，不得出现第二条同号入栏。
"""
import pytest

from app.services import 装载, 目录, 升格回放, 夹具


def _坏点编号(报文编号: str) -> int:
    行 = [r for r in 目录.坏点列表() if r["报文编号"] == 报文编号]
    assert 行, f"夹具未产出坏点:{报文编号}"
    return 行[0]["编号"]


def test_升格带原旁路键进当前栏缓冲():
    装载.装一批(夹具.读取("坏点样例"))
    匣号 = _坏点编号("P-bad-1")

    报告 = 升格回放.升格回放({"坏点编号": [匣号]})

    assert 报告["升格"] == 1
    assert 报告["销匣"] == 1
    指纹 = 报告["指纹"]
    缓冲 = [r for r in 目录.缓冲列表() if r["报文编号"] == "P-bad-1"]
    assert len(缓冲) == 1, "升格只许产生一条入栏，原旁路键随行"
    行 = 缓冲[0]
    assert 行["命运"] == "在栏"
    assert 行["升格指纹"] == 指纹
    assert 行["来源坏点编号"] == 匣号
    报文 = {r["报文编号"]: r for r in 目录.报文列表()}["P-bad-1"]
    assert 报文["命运"] == "已升格"


def test_无键回放切流拒绝():
    装载.装一批(夹具.读取("坏点样例"))

    with pytest.raises(ValueError, match="指纹|键"):
        升格回放.升格回放({})
    with pytest.raises(ValueError, match="指纹|键"):
        升格回放.升格回放({"坏点编号": []})

    # 拒绝后不得留下半条入栏或半条账册
    assert 目录.缓冲列表() == []
    assert 升格回放.只读() == []


def test_升格后同号新装不得复制第二条入栏():
    装载.装一批(夹具.读取("坏点样例"))
    匣号 = _坏点编号("P-bad-1")
    升格回放.升格回放({"坏点编号": [匣号]})

    # 把升格报文当"全新报文"再灌一次：必须幂等驳回，不许产生第二行
    复灌 = {
        "批次编号": "复灌",
        "报文": [{
            "报文编号": "P-bad-1",
            "站点键": "站-河东",
            "指标键": "PM25",
            "读数": 32.0,
            "观测时": "2026-11-24T10:00:00Z",
        }]
    }
    报告 = 装载.装一批(复灌)
    assert 报告["驳回"] == 1
    assert 报告["入栏"] == 0
    同号 = [r for r in 目录.缓冲列表() if r["报文编号"] == "P-bad-1"]
    assert len(同号) == 1, "同号入栏出现第二条即双命运，红"


def test_同指纹二次回放被账册拒绝():
    装载.装一批(夹具.读取("坏点样例"))
    匣号 = _坏点编号("P-bad-1")
    头次 = 升格回放.升格回放({"坏点编号": [匣号]})

    with pytest.raises(ValueError, match="指纹|幂等"):
        升格回放.升格回放({"坏点编号": [匣号], "升格指纹": 头次["指纹"]})

    同号 = [r for r in 目录.缓冲列表() if r["报文编号"] == "P-bad-1"]
    assert len(同号) == 1
